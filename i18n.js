  // capture English from the markup as the source of truth
  const enDict={}, enPh={};
  document.querySelectorAll('[data-i18n]').forEach(el=>{enDict[el.dataset.i18n]=el.innerHTML});
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{enPh[el.dataset.i18nPh]=el.placeholder});

  const FORM_LANG={en:"English",ua:"Ukrainian",ru:"Russian"};
  let currentLang='en';

  function setLang(l){
    if(!['en','ua','ru'].includes(l)) l='en';
    currentLang=l;
    const d=l==='en'?enDict:I18N[l];
    document.querySelectorAll('[data-i18n]').forEach(el=>{
      const k=el.dataset.i18n;
      if(d[k]!=null) el.innerHTML=d[k];
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
      const k=el.dataset.i18nPh;
      const v=l==='en'?enPh[k]:I18N[l][k];
      if(v!=null) el.placeholder=v;
    });
    document.documentElement.lang=l==='ua'?'uk':l;
    document.title=META[l].title;
    const md=document.querySelector('meta[name="description"]');
    if(md) md.setAttribute('content',META[l].desc);
    document.querySelectorAll('#langSwitch button').forEach(b=>b.classList.toggle('active',b.dataset.lang===l));
    // keep the form's "preferred language" in sync with the site language
    const sel=document.getElementById('language');
    if(sel) sel.value=FORM_LANG[l];
    // reflow any open FAQ answer to its new text height
    document.querySelectorAll('.faq-item.open .faq-a').forEach(a=>{a.style.maxHeight=a.scrollHeight+'px'});
    try{localStorage.setItem('cp-lang',l)}catch(e){}
    applyCtaVariant();
  }

